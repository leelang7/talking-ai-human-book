# -*- coding: utf-8 -*-
"""
쪽수 산정 — 한 곳에서만 계산한다

두 스크립트가 서로 다른 쪽수를 보고하던 것을 합친 모듈이다.
`qc.py` 는 353쪽, 직접 센 값은 273쪽이었다. 차이는 **무엇을 글자로 세는가**
하나였다 — 한쪽은 마크다운 기호와 공백까지 세고 있었다.

`**굵게**` 의 별 넷은 인쇄되지 않는다. 표의 `|` 도, 제목의 `#` 도,
줄바꿈도 마찬가지다. 그것들을 세면 원고가 실제보다 30% 두꺼워 보인다.

## 산정 근거

인쇄되는 글자만 세고 **쪽당 700자** 로 나눈다.

    판형 본문       152 × 225mm
    본문 10.5pt     한 줄 약 38자
    행간 1.7        한 쪽 약 30줄
    ────────────────────────────
    빽빽한 산문     약 1,140자/쪽
    구조 할인 40%   제목 · 빈 줄 · 코드블록 · 표 · 도판
    ────────────────────────────
    실효           약 700자/쪽

**이 값은 추정이다.** 진짜 쪽수는 조판 교정쇄에서 나온다. 그때 이 상수 하나만
고치면 모든 스크립트가 같이 따라온다 — 그러라고 여기 모아 둔 것이다.
"""
import re

CHARS_PER_PAGE = 700

# 인쇄되지 않는 마크다운 기호
_SYNTAX = re.compile(r"""
      ^\#{1,6}\s+           # 제목 표시
    | ^\s*>\s?              # 인용 표시
    | ^\s*[-*+]\s+          # 목록 표시
    | ^\s*\d+\.\s+          # 번호 목록
    | ^\s*\|[-: |]+\|\s*$   # 표 구분선
    | \*{1,3}               # 강조
    | `{1,3}                # 코드 표시
    | ^\s*-{3,}\s*$         # 수평선
    | \|                    # 표 칸막이
""", re.M | re.X)

_LINK = re.compile(r"\[([^\]]*)\]\([^)]*\)")     # [글자](주소) → 글자
_IMAGE = re.compile(r"!\[[^\]]*\]\([^)]*\)")     # 도판은 글자가 아니다


def printed_chars(text: str) -> int:
    """실제로 인쇄되는 글자 수. 마크다운 기호와 공백은 빼고 센다."""
    t = _IMAGE.sub("", text)
    t = _LINK.sub(r"\1", t)
    t = _SYNTAX.sub("", t)
    return len(re.sub(r"\s", "", t))


def pages(text: str) -> float:
    return printed_chars(text) / CHARS_PER_PAGE


def fmt(text: str) -> str:
    return f"{pages(text):.0f}p"


def total(texts) -> tuple[int, float]:
    """(글자 수, 쪽수)"""
    c = sum(printed_chars(t) for t in texts)
    return c, c / CHARS_PER_PAGE
